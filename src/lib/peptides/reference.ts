// Pre-lowercased search text for a compound: name, aliases, plain summary,
// what it's studied for, and its benefit lines.
export function referenceHaystack(c: PeptideReference): string {
  return [c.name, c.aka, c.summary, c.studiedFor, ...(c.benefits ?? [])]
    .join(" ")
    .toLowerCase();
}
